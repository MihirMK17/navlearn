#!/usr/bin/env python3
"""Generate LaTeX tables for Paper 1 from aggregated NavLearn results.

Reads results/phase_comparison/ttc_ttr_aggregated.csv and emits:
  docs/paper1/tables/table_phase_comparison.tex   — TTC/TTR success rates all phases
  docs/paper1/tables/table_amcl_ablation.tex      — TTR Phase2 vs Phase2b ablation

Usage:
    python3 generate_paper_tables.py
    python3 generate_paper_tables.py --csv path/to/aggregated.csv
    python3 generate_paper_tables.py --dry-run
"""

import argparse
import csv
import datetime
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[3]
DEFAULT_CSV = REPO_ROOT / "results/phase_comparison/ttc_ttr_aggregated.csv"
DEFAULT_PHASE1_TTC = REPO_ROOT / "results/phase1_ttc"
DEFAULT_PHASE2_TTC = REPO_ROOT / "results/phase2_ttc"
OUT_DIR = REPO_ROOT / "docs/paper1/tables"

LEVELS = ["easy", "medium", "hard", "extreme"]
LEVEL_LABELS = {"easy": "Easy", "medium": "Medium", "hard": "Hard", "extreme": "Extreme"}

PHASE_ORDER = ["phase1", "phase2", "phase2b", "phase3_mppi_baseline", "phase3_mppi_aggressive"]
PHASE_LABELS = {
    "phase1": r"\textbf{Phase 1} (RPP baseline)",
    "phase2": r"\textbf{Phase 2} (AMCL tuned)",
    "phase2b": r"\textbf{Phase 2b} ($\alpha_\text{fast}$ fix)",
    "phase3_mppi_baseline": r"\textbf{Phase 3} (MPPI baseline)",
    "phase3_mppi_aggressive": r"\textbf{Phase 3} (MPPI aggressive)",
}


def load_csv(csv_path: pathlib.Path) -> dict:
    """Load aggregated CSV into nested dict: data[phase][mode][level] = row."""
    data = {}
    with csv_path.open() as f:
        for row in csv.DictReader(f):
            phase = row["phase"]
            mode = row["mode"]
            level = row["level"]
            data.setdefault(phase, {}).setdefault(mode, {})[level] = row
    return data


def fmt_pct(val: str) -> str:
    """Format float string as integer percentage."""
    try:
        return f"{float(val):.0f}"
    except (ValueError, TypeError):
        return "---"


def fmt_delta(val_a: str, val_b: str) -> str:
    """Format signed percentage-point delta (val_b - val_a)."""
    try:
        delta = float(val_b) - float(val_a)
        sign = "+" if delta >= 0 else ""
        return f"{sign}{delta:.0f}"
    except (ValueError, TypeError):
        return "---"


def _load_false_success_counts(ttc_dir: pathlib.Path) -> dict:
    """Return per-level {nav_ok, true_s, false_s} counts from TTC CSVs."""
    counts = {lv: {"nav_ok": 0, "true_s": 0, "false_s": 0} for lv in LEVELS}
    episodes: dict = {}
    for level in LEVELS:
        level_dir = ttc_dir / level
        if not level_dir.exists():
            continue
        for pat in ("localization_metrics_run_*.csv", "navlearn_metrics_run_*.csv"):
            for csv_file in sorted(level_dir.glob(pat)):
                with csv_file.open() as f:
                    reader = csv.DictReader(f)
                    if "GoalID" not in (reader.fieldnames or []):
                        continue
                    for row in reader:
                        gid = row["GoalID"]
                        name = row["Metric Name"]
                        val = row["Metric Value"]
                        episodes.setdefault(gid, {"level": level})
                        if name == "TTC Outcome":
                            episodes[gid]["ttc_outcome"] = val
                        elif name == "Goal Result":
                            episodes[gid]["goal_result"] = val
    for ep in episodes.values():
        lv = ep.get("level", "")
        if lv not in counts:
            continue
        nav_ok = ep.get("goal_result", "").strip() == "1"
        ttc_ok = ep.get("ttc_outcome", "").strip() == "1"
        if not nav_ok:
            continue
        counts[lv]["nav_ok"] += 1
        if ttc_ok:
            counts[lv]["true_s"] += 1
        else:
            counts[lv]["false_s"] += 1
    return counts


def table_false_success(ph1_dir: pathlib.Path, ph2_dir: pathlib.Path) -> str:
    """Generate false-success gap table (Phase 1 vs Phase 2)."""
    today = datetime.date.today().isoformat()
    c1 = _load_false_success_counts(ph1_dir) if ph1_dir.exists() else {}
    c2 = _load_false_success_counts(ph2_dir) if ph2_dir.exists() else {}

    if not c1:
        return f"% Phase 1 TTC dir not found: {ph1_dir}\n"

    lines = [
        f"% Auto-generated by generate_paper_tables.py on {today}",
        r"\begin{table}[t]",
        r"\caption{False-Success Gap by Perturbation Level. "
        r"\emph{NavOK}: Nav2 reports \texttt{SUCCEEDED}. "
        r"\emph{TrueS}: NavOK \emph{and} AMCL converged. "
        r"\emph{FalseS}: NavOK \emph{and} AMCL not converged (TTC\,$=-1$). "
        r"25 trials per level per phase.}",
        r"\label{tab:false_success}",
        r"\centering",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r" & \multicolumn{3}{c}{\textbf{Phase~1}} & \multicolumn{2}{c}{\textbf{Phase~2}} \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}",
        r"\textbf{Level} & \textbf{NavOK} & \textbf{TrueS} & \textbf{FalseS (\%)}"
        r" & \textbf{TrueS} & \textbf{FalseS (\%)} \\",
        r"\midrule",
    ]

    tot1 = {"nav_ok": 0, "true_s": 0, "false_s": 0}
    tot2 = {"nav_ok": 0, "true_s": 0, "false_s": 0}
    for lv in LEVELS:
        r1 = c1.get(lv, {})
        r2 = c2.get(lv, {})
        n1, ts1, fs1 = r1.get("nav_ok", 0), r1.get("true_s", 0), r1.get("false_s", 0)
        ts2, fs2 = r2.get("true_s", 0), r2.get("false_s", 0)
        n2 = r2.get("nav_ok", 0)
        for k in ("nav_ok", "true_s", "false_s"):
            tot1[k] += r1.get(k, 0)
            tot2[k] += r2.get(k, 0)
        pct1 = f"{100*fs1//n1}\\%" if n1 else "---"
        pct2 = (f"{100*fs2//n2}\\%" if n2 else "---") if c2 else "---"
        ts2_str = str(ts2) if c2 else "---"
        pct2_str = pct2
        lines.append(
            rf"{LEVEL_LABELS[lv]} & {n1} & {ts1} & {fs1}\,({pct1})"
            rf" & {ts2_str} & {fs2}\,({pct2_str}) \\"
        )

    n_tot1 = tot1["nav_ok"]
    n_tot2 = tot2["nav_ok"]
    fp1 = f"{100*tot1['false_s']//n_tot1}\\%" if n_tot1 else "---"
    fp2 = (f"{100*tot2['false_s']//n_tot2}\\%" if n_tot2 else "---") if c2 else "---"
    lines += [
        r"\midrule",
        rf"\textbf{{Total}} & {n_tot1} & {tot1['true_s']} & "
        rf"\textbf{{{tot1['false_s']}\,({fp1})}}"
        rf" & {tot2['true_s']} & \textbf{{{tot2['false_s']}\,({fp2})}} \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def table_phase_comparison(data: dict) -> str:
    """Generate TTC + TTR success rate table across all available phases."""
    present_phases = [p for p in PHASE_ORDER if p in data]
    if not present_phases:
        return "% No phase data found\n"

    today = datetime.date.today().isoformat()
    col_spec = "ll" + "c" * len(present_phases)

    header_cells = " & ".join(
        r"\multicolumn{1}{c}{" + PHASE_LABELS.get(p, p) + "}" for p in present_phases
    )

    lines = [
        f"% Auto-generated by generate_paper_tables.py on {today}",
        r"\begin{table*}[t]",
        r"\caption{Localization Recovery Success Rate (\%) by Phase and Perturbation Level. "
        r"TTC = Time-to-Convergence (kidnap disabled). "
        r"TTR = Time-to-Recovery (kidnap enabled, teleport). "
        r"25 episodes per cell (5 goals $\times$ 5 runs).}",
        r"\label{tab:phase_comparison}",
        r"\centering",
        r"\setlength{\tabcolsep}{6pt}",
        rf"\begin{{tabular}}{{{col_spec}}}",
        r"\toprule",
        rf"\textbf{{Mode}} & \textbf{{Level}} & {header_cells} \\",
        r"\midrule",
    ]

    for mode in ["ttc", "ttr"]:
        mode_label = "TTC" if mode == "ttc" else "TTR"
        first_in_mode = True
        for level in LEVELS:
            cells = []
            for phase in present_phases:
                row = data.get(phase, {}).get(mode, {}).get(level)
                if row:
                    cells.append(fmt_pct(row["success_rate_pct"]))
                else:
                    cells.append("---")

            mode_col = rf"\multirow{{{len(LEVELS)}}}{{*}}{{{mode_label}}}" \
                if first_in_mode else ""
            first_in_mode = False
            cell_str = " & ".join(cells)
            lines.append(rf"{mode_col} & {LEVEL_LABELS[level]} & {cell_str} \\")

        if mode == "ttc":
            lines.append(r"\midrule")

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
    ]
    return "\n".join(lines) + "\n"


def table_amcl_ablation(data: dict) -> str:
    """Generate TTR ablation table: Phase 1 vs Phase 2 vs Phase 2b."""
    today = datetime.date.today().isoformat()
    phases = ["phase1", "phase2", "phase2b"]
    present = [p for p in phases if p in data]

    if len(present) < 2:
        return "% Insufficient phase data for ablation table\n"

    lines = [
        f"% Auto-generated by generate_paper_tables.py on {today}",
        r"\begin{table}[t]",
        r"\caption{AMCL Parameter Ablation (TTR, kidnap enabled). "
        r"Phase~2 introduces aggressive beam model tuning; "
        r"Phase~2b isolates the effect of restoring $\alpha_\text{fast}=0.1$. "
        r"$\Delta$ columns show percentage-point change vs. Phase~1.}",
        r"\label{tab:amcl_ablation}",
        r"\centering",
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        r"\textbf{Level} & \textbf{Ph.1} & \textbf{Ph.2} & $\Delta_{1\to2}$ "
        r"& \textbf{Ph.2b} & $\Delta_{1\to\text{2b}}$ \\",
        r"& (\%) & (\%) & (pp) & (\%) & (pp) \\",
        r"\midrule",
    ]

    p1 = data.get("phase1", {}).get("ttr", {})
    p2 = data.get("phase2", {}).get("ttr", {})
    p2b = data.get("phase2b", {}).get("ttr", {})

    for level in LEVELS:
        r1 = p1.get(level, {}).get("success_rate_pct", "")
        r2 = p2.get(level, {}).get("success_rate_pct", "")
        r2b = p2b.get(level, {}).get("success_rate_pct", "")

        d12 = fmt_delta(r1, r2) if r2 else "---"
        d12b = fmt_delta(r1, r2b) if r2b else "---"

        lines.append(
            f"{LEVEL_LABELS[level]} & {fmt_pct(r1)} & {fmt_pct(r2)} & {d12} "
            f"& {fmt_pct(r2b)} & {d12b} \\\\"
        )

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def write_table(path: pathlib.Path, content: str, dry_run: bool) -> None:
    """Write table file, or print path + preview in dry-run mode."""
    if dry_run:
        print(f"[dry-run] Would write: {path}")
        print(content[:300] + ("..." if len(content) > 300 else ""))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(f"[generate_paper_tables] Written: {path}")


def parse_args() -> argparse.Namespace:
    """Parse CLI arguments."""
    parser = argparse.ArgumentParser(description="Generate LaTeX tables for Paper 1")
    parser.add_argument("--csv", type=pathlib.Path, default=DEFAULT_CSV,
                        help="Path to ttc_ttr_aggregated.csv")
    parser.add_argument("--phase1-ttc", type=pathlib.Path, default=DEFAULT_PHASE1_TTC,
                        help="Phase 1 TTC results directory (for false-success table)")
    parser.add_argument("--phase2-ttc", type=pathlib.Path, default=DEFAULT_PHASE2_TTC,
                        help="Phase 2 TTC results directory (for false-success table)")
    parser.add_argument("--out-dir", type=pathlib.Path, default=OUT_DIR,
                        help="Output directory for .tex files")
    parser.add_argument("--dry-run", action="store_true",
                        help="Print output paths without writing")
    return parser.parse_args()


def main() -> None:
    """Load CSV and emit all tables."""
    args = parse_args()

    if not args.csv.exists():
        print(f"[generate_paper_tables] ERROR: {args.csv} not found", file=sys.stderr)
        print("Run analyze_ttc_ttr.py first to produce the aggregated CSV.", file=sys.stderr)
        sys.exit(1)

    data = load_csv(args.csv)
    phases_found = sorted(data.keys())
    print(f"[generate_paper_tables] Phases in CSV: {phases_found}")

    write_table(
        args.out_dir / "table_phase_comparison.tex",
        table_phase_comparison(data),
        args.dry_run,
    )
    write_table(
        args.out_dir / "table_amcl_ablation.tex",
        table_amcl_ablation(data),
        args.dry_run,
    )
    write_table(
        args.out_dir / "table_false_success.tex",
        table_false_success(args.phase1_ttc, args.phase2_ttc),
        args.dry_run,
    )


if __name__ == "__main__":
    main()
